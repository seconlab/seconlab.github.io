<A NAME="revision"></A>
<P><B><I>Revision</I></B><BR>
The procedure for electronically submitting a revision through a <A
HREF="revise.php">Revision Form</a> is similar to the procedure
described earlier for <A HREF="#submission">submission.</A> The difference
is that you must supply a Unique ID that was sent to you via email after we
receive your original submission. The rest of the fields are the same and
are optional. Once a revision is received, an email notification will be
sent to the specified contact person. If this email address is different
from the previous contact, a notification will also be sent to the previous
contact email address.<P>


