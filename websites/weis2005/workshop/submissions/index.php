<A NAME="introduction"></A>
<FONT SIZE=-1><B>INTRODUCTION</B><BR><BR>

This is a working document describing the electronic submission procedure
for the Workshop on Economics of Information Security. All electronic submissions must be
submitted through the <A HREF="#esub">web interface</A> (no email or ftp);
they must arrive by
<B>March 6, 2005, 23:59:59, EST</B>.
The server will begin operation on <B>February 1, 2001</B>.

<P>Questions about the submission process may be sent to <B>
<A HREF=mailto:infosecon@infosecon.net>infosecon@infosecon.net</A></B>.

<P>To upload your submission, you will need to
use a RFC 1867-compliant browser. 

<P>While we will try hard to make sure that the submission software runs flawlessly up to the deadline, bugs do come up, 
particularly when the server is likely to be under a high load with lots of traffic. For
this reason we request that you submit your paper as early as possible.

<P>In addition, please keep in mind the following:<UL>
  <LI>When you send in a submission, the server generates an MD5 "receipt"
  for the submission. In case of serious server error, this lets you "prove"
  to us that the submission arrived. <I>We strongly recommend that you keep
  your original PostScript</I> file until after the deadline so that it can
  be used in conjunction with the receipt for verification.<BR>
  You can also compute a md5-checksum of your original file and compare it
  against the "receipt" to be sure that we have received your submission
  without errors. On most UNIX-platforms the program <CODE>md5sum</CODE>
  should already be installed. On Windows-platforms there exist versions of
  this program, too (see, e.g., "Cygwin" together with the "textutils"-package
  at <A HREF="http://sources.redhat.com/cygwin/">http://sources.redhat.com/cygwin/</A>
  or "GNU utilities for Win32"
  at <A HREF="http://www.edv.agrar.tu-muenchen.de/~syring/win32/UnxUtils.html">
  http://www.edv.agrar.tu-muenchen.de/~syring/win32/UnxUtils.html</A>).</LI>

  <LI> Withdrawals before the deadline can be done using the electronic
  submissions system (for papers that have been submitted electronically);
  please see the section <i><A HREF="#esub">basic procedure</A></i> for
  details. Withdrawals after the deadline will need to be arranged through
  the program chair.</LI>
  </UL>
</FONT>


