<A NAME="format"></A>
<FONT SIZE=-1><B>FORMATTING THE PAPER</B><BR><BR>

We understand that many papers will cross disciplinary boundaries, and some may reasonably fit in
all three categories below. The person submitting should select or balance the guidelines appropriately for their work.
<UL> 
	<LI> Social Science Papers
		<UL>
		<LI> Margins: All margins 1 inch each </LI>
		<LI> Page length: Maximum 20 pages</LI>
		<LI> File Format: PDF
		</UL>
		Position papers of significantly shorter length are also welcome.
		
	</LI><BR>
        <LI> Law and Economics Papers
                <UL>
                <LI> Margins: All margins 1 inch each </LI>
                <LI> Page length: Maximum 30 pages including footnotes and appendices </LI>
		<LI> File Format: PDF
                </UL>
                Position papers of significantly shorter length are also welcome.

        </LI><BR>
        <LI> Computer Science Papers
                <UL>
                <LI> Page length: Maximum 15 pages or 8000 words </LI>
                <LI> File Format: PS or PDF </LI>
                </UL>
                Position papers of significantly shorter length are also welcome.

        </LI>

</UL>
