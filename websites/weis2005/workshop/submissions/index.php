<A NAME="esub"></A>
<FONT SIZE=-1><B>BASIC PROCEDURE</B><BR><BR>

<A NAME="submission"></A>
<P><B><I>Submission</I></B><BR>

The electronic submission procedure involves filling out a <A
HREF="submit.php">Submission Form</A> through the web
interface. The form has the following fields:

<P><TABLE BGCOLOR=#DDDDDD CELLPADDING=1 CELLSPACING=2 WIDTH=100%>
  <TR VALIGN=TOP>
    <TD><FONT FACE="Arial,Helvetica,sans-serif" SIZE=-1>Title:</FONT></TD>
    <TD><FONT FACE="Arial,Helvetica,sans-serif" SIZE=-1>title of document.</FONT></TD></TR>
  <TR VALIGN=TOP>
    <TD><FONT FACE="Arial,Helvetica,sans-serif" SIZE=-1>Contact:</FONT></TD>
    <TD><FONT FACE="Arial,Helvetica,sans-serif" SIZE=-1>e-mail address of a contact person for this paper.</FONT></TD></TR>
  <TR VALIGN=TOP>
    <TD><FONT FACE="Arial,Helvetica,sans-serif" SIZE=-1>Authors:</FONT></TD>
    <TD><FONT FACE="Arial,Helvetica,sans-serif" SIZE=-1>list of authors separated by "and".</FONT></TD></TR>
  <TR><TD><FONT FACE="Arial,Helvetica,sans-serif" SIZE=-1>Affiliations:</ FONT></TD>
      <TD><FONT FACE="Arial,Helvetica,sans-serif" SIZE=-1>list of the respective affiliations of the authors separated by "and".</FONT></TD></TR>
  <TR><TD><FONT FACE="Arial,Helvetica,sans-serif" SIZE=-1>Abstract:</ FONT></TD>
      <TD><FONT FACE="Arial,Helvetica,sans-serif" SIZE=-1>abstract of your paper</FONT></TD></TR>
  <TR VALIGN=TOP>
    <TD><FONT FACE="Arial,Helvetica,sans-serif" SIZE=-1>Paper:</FONT></TD>
    <TD><FONT FACE="Arial,Helvetica,sans-serif" SIZE=-1>full pathname of the file to be uploaded. You can use the browse button to help select the file.</FONT></TD></TR>
</TABLE>

<P>The contents of the authors and contacts fields will be used in
processing the documents, but will not be read by the program
committee. Also, note that any newline character encountered in these
entries will be ignored.

<P>It is possible to <I>practice</I> submitting a paper before doing
the real submission. Simply fill out all the fields and submit the
form. You will receive an MD5 receipt and a unique id for the
submission. Then, you can upload as many revisions as you would like
using the given unique id.

