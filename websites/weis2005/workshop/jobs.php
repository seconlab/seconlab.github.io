<td>        
University of Michigan and Wayne
State University <a href="http://stiet.si.umich.edu/">STIET-Incentive-Centered Design
Program</a>

The <b>STIET</b> program brings
together faculty and doctoral students from the University of Michigan and
Wayne State University in research, training, and outreach, through an
incentive-centered design (ICD) approach to modern information systems. System
performance depends on the strategic behavior of autonomous, self-interested
humans; therefore we draw on theories of rational decision making,
game-theoretic models of strategic interaction, and economic, psychological and
other social science theories of motivation to form a principled grounding for
system design. <a
href="http://stiet.si.umich.edu/">STIET </a>students and faculty collaborate in
interdisciplinary ICD research fueled by a weekly seminar series and twice
yearly research workshops.&nbsp; Our program provides curriculum, research training and a collaborative research community. Generous NSF IGERT-funded fellowships are available.  We also have a new summer research training and mentoring program to prepare and encourage promising undergraduates and masters students to pursue a graduate degree, and will provide a training ground in research leadership and mentoring for our PhD students, called the STIET-Summer Research Opportunity Program (S-SROP)

