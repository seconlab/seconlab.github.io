The School of Informatics at Indiana University offers a PhD in  <a href="http://xavier.informatics.indiana.edu/gradsites/security/PhD/">Security Informatics</a>
Security Informatics is centered on the core protocols and practices of information technology security and its use. The Security Informatics curriculum includes all subjects central to computer security: mathematics, protocol analysis, system and network security. It also naturally dovetails with the span of material pertaining to informatics. Indeed, Security Informatics is security integrated with human-computer interaction, social engineering, science informatics, and information technology rather than isolated from the large economic and social milieu.

