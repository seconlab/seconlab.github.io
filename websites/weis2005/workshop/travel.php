        <p><img src="harvard.jpg" width="400" height="208"></p>
        <h1> ACCOMMODATIONS</h1>
        <p><strong>PLEASE NOTE: Thursday, June 2 and Friday, June 3, 2005 
          are extremely busy days around Harvard Square. Harvard and MIT are both 
          holding reunions and commencement ceremonies on and near those dates. 
          Please make your reservations at one of the nearby hotals as soon as 
          possible.</strong></p>
	
	The Harvard Square Hotel and the Inn at Harvard are fully booked, but we can recommend several other hotels in the area.
        <UL>
	<LI> <A HREF="http://www.sheratoncommander.com/accommodations.htm"> Sheraton Commander Hotel</A>, Harvard Square (about .5 miles from KSG), with
	 rates starting at $189/nt. Call (888) 627-7121 and ask for a 
	reserved room under the "Workshop on the Economics of Information Security"</p>
	<LI><A HREF="http://www.doubletree.com/en/dt/hotels/index.jhtml?moreDesc=true&ctyhocn=BOSSBDT">Doubletree Guest Suites Boston</A> is across the 
river (about 1.5 miles by foot) and has some rooms available. Call 617-783-0090.</p>
	<LI>For luxury accomodations next to the KSG, call <a href="http://www.charleshotel.com/">The 
          Charles Hotel</a> (617)864-1200. </p>
	<LI>Students and those seeking to economize may want to use our <A HREF="http://www.designforvalues.org/cgi-bin/wiki.pl?ConferenceRoomShare">room-sharing wiki</A>.
	</UL>
