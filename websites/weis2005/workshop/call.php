      <td width="611" height="380" valign="top"> <h1 align="center"><br>
          Call for Papers WEIS 2005</h1>
        <p align="center"><font color="#CC3333">Fourth Workshop on the Economics 
          of Information Security<br>
          Kennedy School of Government<br>
          Harvard University<br>
          2 - 4 June 2005</font></p>
        <p align="left"><strong>Call for Papers</strong><br>
          [PDF available <a href="../workshop/cfp.pdf">here</a>]</p>
        <p>Original Research Papers on all aspects of the Economics of Information 
          Security are solicited for submission to the Fourth Workshop on the 
          Economics of Information Security. Topics of interest include liability 
          and other legal incentives, game theoretic models, economics of digital 
          rights management, security in open source and free software, cyber-insurance, 
          disaster recovery, trusted computing, reputation economics network effects 
          in security and privacy, security in grid computing, return on security 
          investment, security and privacy in pervasive computing, risk management, 
          risk perception, economics of trust, virus models, vulnerabilities and 
          incentives, economics of malicious code, identity including PKI, access 
          control, economics of electronic voting security, and economic perspectives 
          on spam.</p>
        <p>We invite talks emphasizing economic theory, mathematical modeling, 
          or legal theory. Past notable work used the tools of economics to offer 
          insights into computer security; offered mathematical models of computer 
          security or economics; detailed potential regulatory solutions to computer 
          security; or clarified the challenges of improving security as implemented 
          in practice. </p>
