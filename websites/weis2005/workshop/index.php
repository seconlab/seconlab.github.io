      <td width=491 rowspan="3" valign="top" style="padding:25px"> <h1> Fourth 
          Workshop on the Economics of Information Security </h1>
        <h4> <strong>was held on the campus of </strong></h4>
        <h1>Kennedy School of Government<br>
          Harvard University<br>
          <br>
          2 - 3 June 2005</h1>
        <p>The Fourth Workshop on the Economics of Information Security addressed 
          the problems of privacy security using the tools, techniques, and concepts 
          of economics. Theoretical and practical aspects of computer security 
          and economics, proposals for legal mechanisms, empirical examinations 
          of fielded systems, and reports on experiments were presented. Computer 
          scientists, scholars of law, economists, accountants, policy analysts, 
          and social scientists contributed.</p>
        <p> Papers and presentations can be found in the <A href=schedule.php>schedule</a> 
          section of this website. Notes from the Workshop are available at<A href="http://allan.friedmans.org/conferences/WEIS_2005.html"> 
          allan.friedmans.org/conferences</a>. </p>
        <p> My thanks to all who contributed. I would like to thank the authors 
          and presentors for providing excellent content. I would like to thank 
          my students Alla Genkina and, in particular, Allan Friedman. I owe my 
          thanks to the members of the program committee. Thanks as well to the 
          organizer, Lori Uhland of Rare Events.<br>
          <br>
          --<A href=http://www.ljean.com>L Jean Camp</a><br>
          Chair<br>
          WEIS '05</p>
        <p> <strong><U>WEIS06</U>: The Fifth Workshop on the Economics of Information 
          Security will be held at the University of Cambridge, England, 26-28 
          June 2006. The initial call for papers is available <A HREF="http://www.cl.cam.ac.uk/users/twm29/WEIS06/">here</A> 
          </strong> </p>
